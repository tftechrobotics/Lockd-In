#!/usr/bin/env python3
"""Export the Cream & Ink design system to the Android app.

  python3 design/export-android.py      (needs: pip install fonttools brotli)

Writes into apps/android/app/src/main:
  java/app/lockdin/ui/Tokens.kt      colors from design/tokens.json
  res/font/*.ttf                     static Outfit/Figtree instances (OFL)
  res/drawable/wordmark.xml, lock_mark.xml   vectors from design/assets/*.svg
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "apps/android/app/src/main"
tokens = json.loads((ROOT / "design/tokens.json").read_text())

# --- Colors -> Kotlin ---------------------------------------------------------
def argb(v):
    v = v.strip()
    if v.startswith("#"):
        return "0xFF" + v[1:].upper()
    m = re.match(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", v)
    r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
    return "0x%02X%02X%02X%02X" % (round(a * 255), r, g, b)

def palette(name, c):
    lines = [f"    {k} = Color({argb(v)})," for k, v in c.items() if isinstance(v, str)]
    return f"val {name} = LockdInColors(\n" + "\n".join(lines) + "\n)"

keys = [k for k, v in tokens["color"]["light"].items() if isinstance(v, str)]
kt = f'''// Generated by design/export-android.py from design/tokens.json. Do not edit.
package app.lockdin.ui

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
data class LockdInColors(
{chr(10).join(f"    val {k}: Color," for k in keys)}
)

{palette("LightColors", tokens["color"]["light"])}

{palette("DarkColors", tokens["color"]["dark"])}
'''
(APP / "java/app/lockdin/ui/Tokens.kt").write_text(kt)

# --- Fonts --------------------------------------------------------------------
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
fonts = ROOT / "apps/web/node_modules/@fontsource-variable"
if not fonts.exists():
    sys.exit("Run `npm ci` in apps/web first (fonts come from @fontsource-variable).")
for fam, file, weights in [("outfit", "outfit/files/outfit-latin-wght-normal.woff2", [500, 600, 700, 800]),
                           ("figtree", "figtree/files/figtree-latin-wght-normal.woff2", [400, 500, 600])]:
    for w in weights:
        f = TTFont(fonts / file)
        f.flavor = None
        instantiateVariableFont(f, {"wght": w}, inplace=True)
        f.save(APP / f"res/font/{fam}_{w}.ttf")

# --- SVG -> VectorDrawable ----------------------------------------------------
def vector(svg_path, out, tint="#FF302A25"):
    svg = svg_path.read_text()
    vb = [float(x) for x in re.search(r'viewBox="([^"]+)"', svg)[1].split()]
    tf = re.search(r'translate\(0 (-?[\d.]+)\)', svg)
    dy = float(tf[1]) if tf else 0.0
    paths = re.findall(r'<path((?: [a-z-]+="[^"]*")*)/?>', svg)
    items = []
    for attrs in paths:
        d = re.search(r' d="([^"]+)"', attrs)[1]
        even = 'fill-rule="evenodd"' in attrs
        items.append(f'        <path android:fillColor="#FF000000"{" android:fillType=\"evenOdd\"" if even else ""} android:pathData="{d}"/>')
    group_open = f'    <group android:translateY="{dy}">' if dy else "    <group>"
    w, h = vb[2], vb[3]
    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by design/export-android.py from {svg_path.relative_to(ROOT)}. Do not edit. Tinted at use. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w:g}dp" android:height="{h:g}dp"
    android:viewportWidth="{w:g}" android:viewportHeight="{h:g}"
    android:tint="{tint}">
{group_open}
{chr(10).join(items)}
    </group>
</vector>
'''
    (APP / "res/drawable" / out).write_text(xml)

vector(ROOT / "design/assets/wordmark.svg", "wordmark.xml")
vector(ROOT / "design/assets/lock-mark.svg", "lock_mark.xml")
print("exported tokens, fonts, vectors")
