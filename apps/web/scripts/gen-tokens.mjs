// design/tokens.json -> src/styles/tokens.css (CSS custom properties).
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('../../../design/tokens.json', import.meta.url)));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const vars = (o) => Object.entries(o).map(([k, v]) => `  --${kebab(k)}: ${v};`).join('\n');
const css = `/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */
:root {
${vars(t.color.light)}
  --radius-control: ${t.radius.control}px;
  --radius-surface: ${t.radius.surface}px;
  --radius-lock: ${t.radius.lock}px;
  --motion: ${t.motion.durationMs}ms ${t.motion.easing};
  color-scheme: light;
}
:root[data-theme="dark"] {
${vars(t.color.dark)}
  color-scheme: dark;
}
`;
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log('tokens.css written');
